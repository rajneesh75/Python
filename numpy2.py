import numpy as np

print(np.zeros((2, 3)))  # array of zeros
print(np.ones((3, 2)))  # array of ones
print(np.full((2, 2), 7))  # fill with constant)

print(np.eye(3))  # identity matrix)

print(np.arange(0, 10, 2))  # [0, 2, 4, 6, 8]
print(np.linspace(0, 1, 5))  # 5 equally spaced points between 0 and 1
